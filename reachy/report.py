"""Daily Outreach & Deliverability Performance Report Generator.

Built by ISIRA Automations for Reachy.
Aggregates daily sending volume, warmup progression, open rates, bounce telemetry,
reply sentiment, and actionable operational insights.
"""

from __future__ import annotations

import json

@dataclass
class DailyReport:
    report_date: str
    generated_at: str
    volume: dict[str, int]
    engagement: dict[str, Any]
    sentiment: dict[str, int]
    deliverability: dict[str, Any]
    accounts_warmup: list[dict[str, Any]]
    insights: list[str]

    def as_dict(self) -> dict[str, Any]:
        return {
            "report_date": self.report_date,
            "generated_at": self.generated_at,
            "volume": self.volume,
            "engagement": self.engagement,
            "sentiment": self.sentiment,
            "deliverability": self.deliverability,
            "accounts_warmup": self.accounts_warmup,
            "insights": self.insights,
        }

    def format_markdown(self) -> str:
        vol = self.volume
        eng = self.engagement
        sent = self.sentiment
        deliv = self.deliverability

        lines = [
            f"# Reachy Daily Outreach Report — {self.report_date}",
            f"*Generated by ISIRA Automations at {self.generated_at} UTC*",
            "",
            "## 1. Executive Outreach Summary",
            "",
            f"| Metric | Today ({self.report_date}) | Total Active Pipeline |",
            "| :--- | :--- | :--- |",
            f"| **Emails Sent** | **{vol.get('sent_today', 0)}** | {vol.get('sent_all_time', 0)} total sent |",
            f"| **Emails Queued/Planned** | **{vol.get('queued_remaining', 0)}** | {vol.get('planned_total', 0)} planned |",
            f"| **Blocked by Policy** | **{vol.get('blocked_today', 0)}** | {vol.get('failed_today', 0)} provider failures |",
            "",
            "## 2. Engagement & Telemetry",
            "",
            f"- **Unique Open Rate**: **{eng.get('unique_open_rate_percent', '0.00%')}** ({eng.get('unique_opens', 0)} unique opens across {eng.get('total_sends', 0)} sent)",
            f"- **Total Open Events**: **{eng.get('total_opens', 0)}** (includes multiple opens / forward reads)",
            f"- **Inbound Replies**: **{eng.get('replies_today', 0)}** (Reply Rate: **{eng.get('reply_rate_percent', '0.00%')}**)",
            "",
            "### Reply Sentiment Breakdown",
            f"- **Interested**: {sent.get('interested', 0)} 🔥",
            f"- **Referral**: {sent.get('referral', 0)} 🤝",
            f"- **Out of Office**: {sent.get('out_of_office', 0)} ⏳",
            f"- **Not Interested**: {sent.get('not_interested', 0)} 🛑",
            f"- **Unsubscribe Requests**: {sent.get('unsubscribe', 0)} ⚠️",
            f"- **Complaints**: {sent.get('complaint', 0)} 🚨",
            "",
            "## 3. Sender Reputation & Deliverability",
            "",
            f"- **Hard Bounces**: **{deliv.get('bounces_today', 0)}** (Bounce Rate: **{deliv.get('bounce_rate_percent', '0.00%')}**)",
            f"- **Suppression Additions**: **{deliv.get('suppressions_today', 0)}**",
            f"- **Health Status**: **{deliv.get('overall_health', 'HEALTHY')}**",
            "",
            "## 4. Account Warmup Fleet Status",
            "",
        ]

        if not self.accounts_warmup:
            lines.append("*(No active sending accounts found)*")
        else:
            lines.append("| Account | Stage | Limit Today | Sent Today | Remaining | Days to Full |")
            lines.append("| :--- | :--- | :--- | :--- | :--- | :--- |")
            for acc in self.accounts_warmup:
                lines.append(
                    f"| `{acc['email']}` | {acc['stage_name']} | {acc['effective_daily_limit']} | {acc['sends_today']} | {acc['remaining_today']} | {acc['days_to_full_warmup']}d |"
                )

        lines.extend([
            "",
            "## 5. Operational Insights & Actions",
            "",
        ])
        for insight in self.insights:
            lines.append(f"- {insight}")

        return "\n".join(lines)


def generate_daily_report(
    db: Database,
    target_date: Optional[date] = None,
    account_id: Optional[int] = None,
) -> DailyReport:
    """Compiles a complete 24-hour outreach report."""
    target_date = target_date or datetime.now(timezone.utc).date()
    date_str = target_date.isoformat()
    now_iso = utcnow()

    # 1. Volume queries
    date_filter = f"{date_str}%"
    sent_today_row = db.fetchone(
        """SELECT COUNT(*) AS c FROM messages
           WHERE state IN ('SENT', 'ACCEPTED') AND (sent_at LIKE ? OR created_at LIKE ?)""",
        (date_filter, date_filter),
    )
    sent_today = int(sent_today_row["c"]) if sent_today_row else 0

    sent_all_row = db.fetchone("SELECT COUNT(*) AS c FROM messages WHERE state IN ('SENT', 'ACCEPTED')")
    sent_all_time = int(sent_all_row["c"]) if sent_all_row else 0

    queued_row = db.fetchone("SELECT COUNT(*) AS c FROM messages WHERE state = 'QUEUED'")
    queued_remaining = int(queued_row["c"]) if queued_row else 0

    planned_row = db.fetchone("SELECT COUNT(*) AS c FROM messages WHERE state = 'PLANNED'")
    planned_total = int(planned_row["c"]) if planned_row else 0

    blocked_row = db.fetchone(
        "SELECT COUNT(*) AS c FROM messages WHERE state = 'BLOCKED' AND updated_at LIKE ?",
        (date_filter,),
    )
    blocked_today = int(blocked_row["c"]) if blocked_row else 0

    failed_row = db.fetchone(
        "SELECT COUNT(*) AS c FROM messages WHERE state = 'FAILED' AND updated_at LIKE ?",
        (date_filter,),
    )
    failed_today = int(failed_row["c"]) if failed_row else 0

    volume = {
        "sent_today": sent_today,
        "sent_all_time": sent_all_time,
        "queued_remaining": queued_remaining,
        "planned_total": planned_total,
        "blocked_today": blocked_today,
        "failed_today": failed_today,
    }

    # 2. Open tracking queries
    open_stats = calculate_open_stats(db, account_id=account_id)
    unique_opens = open_stats["unique_opens"]
    total_opens = open_stats["total_opens"]
    total_sends = open_stats["sent_count"]
    open_rate = open_stats["open_rate"]

    # 3. Replies & Sentiment
    replies_today_rows = db.fetchall(
        "SELECT classification, COUNT(*) AS c FROM replies WHERE received_at LIKE ? GROUP BY classification",
        (date_filter,),
    )
    sentiment: dict[str, int] = {}
    replies_today = 0
    for row in replies_today_rows:
        count = int(row["c"])
        sentiment[row["classification"]] = count
        replies_today += count

    reply_rate = (replies_today / sent_today) if sent_today > 0 else 0.0

    engagement = {
        "total_sends": total_sends,
        "unique_opens": unique_opens,
        "total_opens": total_opens,
        "unique_open_rate": open_rate,
        "unique_open_rate_percent": f"{open_rate * 100:.2f}%",
        "replies_today": replies_today,
        "reply_rate": round(reply_rate, 4),
        "reply_rate_percent": f"{reply_rate * 100:.2f}%",
    }

    # 4. Deliverability & Health
    bounce_events = db.fetchone(
        "SELECT COUNT(*) AS c FROM message_events WHERE event_type = 'HARD_BOUNCE' AND created_at LIKE ?",
        (date_filter,),
    )
    bounces_today = int(bounce_events["c"]) if bounce_events else 0
    bounce_rate = (bounces_today / sent_today) if sent_today > 0 else 0.0

    suppress_today = db.fetchone(
        "SELECT COUNT(*) AS c FROM suppression WHERE created_at LIKE ?",
        (date_filter,),
    )
    suppressions_today = int(suppress_today["c"]) if suppress_today else 0

    deliverability = {
        "bounces_today": bounces_today,
        "bounce_rate": round(bounce_rate, 4),
        "bounce_rate_percent": f"{bounce_rate * 100:.2f}%",
        "suppressions_today": suppressions_today,
        "overall_health": "ALERT" if bounce_rate > 0.04 else "HEALTHY",
    }

    # 5. Accounts Warmup Status
    account_clause = "WHERE id = ?" if account_id else "WHERE status != 'REVOKED'"
    account_params = (account_id,) if account_id else ()
    accounts = db.fetchall(f"SELECT * FROM accounts {account_clause}", account_params)
    warmup_list = []
    for acc in accounts:
        st = get_account_warmup_status(db, int(acc["id"]))
        warmup_list.append(st.as_dict())

    # 6. Operational Insights
    insights: list[str] = []
    if bounce_rate > 0.03:
        insights.append(
            f"⚠️ **Bounce rate is elevated ({bounce_rate * 100:.2f}%)**: Consider re-verifying lead emails before starting tomorrow's batch."
        )
    elif sent_today > 0 and bounces_today == 0:
        insights.append("✅ **Clean Deliverability**: Zero bounces recorded today. Domain reputation remains pristine.")

    if open_rate > 0.40:
        insights.append(
            f"🔥 **Exceptional Open Rate ({open_rate * 100:.2f}%)**: Current subject line style is resonating strongly with recipients."
        )
    elif sent_all_time >= 20 and open_rate < 0.20:
        insights.append(
            "💡 **Subject Line Optimization**: Open rate is below 20%. Consider switching to the 2-3 word 'Casual Mobile Observation' style."
        )

    if sentiment.get("interested", 0) > 0:
        insights.append(
            f"🎯 **{sentiment['interested']} Positive Lead(s)** received today. Reply drafts have been staged in Reachy for human approval."
        )

    if queued_remaining == 0 and planned_total > 0:
        insights.append(
            "📅 Next lead batch is safely scheduled for tomorrow morning within business hours. No manual intervention needed."
        )

    if not insights:
        insights.append("All campaigns and inboxes are operating within safe baseline parameters.")

    return DailyReport(
        report_date=date_str,
        generated_at=now_iso,
        volume=volume,
        engagement=engagement,
        sentiment=sentiment,
        deliverability=deliverability,
        accounts_warmup=warmup_list,
        insights=insights,
    )


def send_daily_report_email(
    db: Database,
    recipient_email: str,
    report: DailyReport,
    account_id: Optional[int] = None,
    provider_factory: Optional[Any] = None,
) -> dict[str, Any]:
    """Emails the generated daily markdown report to the designated administrator/user."""
    if not provider_factory:
        return {"ok": False, "reason": "No provider factory supplied"}

    account = None
    if account_id:
        account = db.fetchone("SELECT * FROM accounts WHERE id = ?", (account_id,))
    else:
        account = db.fetchone("SELECT * FROM accounts WHERE status = 'ACTIVE' LIMIT 1")

    if not account:
        return {"ok": False, "reason": "No active sending account available to dispatch daily report"}

    provider = provider_factory(dict(account))
    try:
        body = report.format_markdown()
        outbound = OutboundMessage(
            from_email=account["email"],
            from_name="Reachy Intelligence",
            to_email=recipient_email,
            subject=f"Daily Outreach Report — {report.report_date}",
            body=body,
            message_id_header=f"<report-{report.report_date}-{account['id']}@reachy.local>",
        )
        result = provider.send(outbound)
        return {"ok": result.status == "accepted", "provider_id": result.provider_message_id, "error": result.error}
    finally:
        provider.close()
